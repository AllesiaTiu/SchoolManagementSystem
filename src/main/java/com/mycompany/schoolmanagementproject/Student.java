package com.mycompany.schoolmanagementproject;



public class Student {
    
    String name;
    String id;

    public Student(String name, String id) {
        this.name = name;
        this.id = id;
    }
    public String getName(){
        return name;
    }
    public String getID(){
        return id;
    }
    
    
    
    
    
}
